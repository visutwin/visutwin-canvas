// Port of upstream render-targets/volume-texture.
//
// Fills a 128 x 128 x 32 volume texture (rgb: fog colour, a: density) with colourful fog and
// raymarches it over the terrain with a fullscreen quad, stopping at the scene geometry by the
// camera's depth map. The volume spans the terrain's bounds from the bottom up to 0.525 of their
// height, its width and height across world x and z and its depth slices stacked up the world
// height. The fog is either static, twelve gaussian blobs filled on the CPU with a seeded random
// generator, or dynamic: the same blobs drifting, rendered on the GPU into the depth slices, a
// render target per slice, eight slices a frame in turn (all 32 on a new volume's first frame).
// With mipmaps the volume's chain is generated from the uploaded level, or, for the dynamic fog,
// after the last slice of each group of eight is rendered. The quad is drawn with the world's
// transparent objects (premultiplied, no depth test), 64 steps a ray with a per-pixel jitter.
// The terrain is lit by the helipad env atlas alone (skybox mip 3, rotated -70 degrees), under
// ACES, the camera at (600, 320, 50) orbiting the bounds centre of a tree in the middle,
// (-4.47, 37.15, 27.63), pitch held to +/-90 degrees and zoom capped at 1800 (far clip 3000).
//
// Keys stand in for upstream's controls panel:
//   [ / ]  density -/+ 0.01 (0 .. 0.2)
//   - / =  brightness -/+ 0.25 (0 .. 4)
//   D      dynamic fog on / off
//   M      mipmaps on / off
//   9 / 0  the mip level sampled -/+ 1 (0 .. 7)
//
// DEVIATIONS:
// - The shaders are Slang (one source for both backends): the raymarch is a ShaderMaterial over
//   getOrCreateSlangShaderFromSource, the volume bound at the material's base colour slot as a
//   Sampler3D, the camera values (inverse view-projection, position, forward, near and far) in
//   the material's uniform block; the slices are quad passes with Slang source.
// - The slice passes render at the START of the frame graph (Renderer::addPrependPass), one per
//   slice, enabled for the slices due that frame, where upstream draws them from the update
//   event. Mips are generated by the passes of slices 7, 15, 23 and 31, which is where upstream's
//   per-target mip level option puts them.
//
// @credit Terrain Low Poly by Sketchfab, CC BY 4.0
//
