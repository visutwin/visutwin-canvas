    /// BlueNoise: a seeded walk over the tile, one RGBA texel per call.
    class BlueNoise
    {
    public:
        explicit BlueNoise(const int seed = 0) : _seed(static_cast<size_t>(seed) * 4) {}

        float value()
        {
            next();
            return static_cast<float>(kBlueNoiseRgba32[_seed]) / 255.0f;
        }

        Vector4 vec4()
        {
            next();
            return Vector4(static_cast<float>(kBlueNoiseRgba32[_seed]) / 255.0f,
                static_cast<float>(kBlueNoiseRgba32[_seed + 1]) / 255.0f,
                static_cast<float>(kBlueNoiseRgba32[_seed + 2]) / 255.0f,
                static_cast<float>(kBlueNoiseRgba32[_seed + 3]) / 255.0f);
        }

    private:
        void next() { _seed = (_seed + 4) % kBlueNoiseRgba32.size(); }

        size_t _seed = 0;
    };
